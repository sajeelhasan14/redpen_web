export function glyph(ch: string): Glyph | undefined {
  const g = G[ch];
  if (g) return g;
  // An uppercase letter without its own glyph is the lowercase one stretched to
  // full height: a plain, legible hand rather than a font fallback mid-word.
  const lower = ch.length === 1 && ch !== ch.toLowerCase() ? G[ch.toLowerCase()] : undefined;
  if (!lower) return undefined;
  return {
    adv: lower.adv * 1.1,
    strokes: lower.strokes.map((path) => path.map(([x, y]) => [x, Math.max(-0.02, Math.min(1.02, (y - 0.42) / 0.58))] as [number, number])),
  };
}
